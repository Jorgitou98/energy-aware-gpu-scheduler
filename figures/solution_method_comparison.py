def group_map(ax, rows):
    means, counts = [], []
    for group, _ in GROUPS:
        selected = [r for r in rows if r["stratum"] == group]
        values = [losses(selected, key) for key, _, _ in METHODS]
        means.append([float(v.mean()) if len(v) else np.nan for v in values])
        counts.append([len(v) for v in values])
    matrix = np.asarray(means)
    cmap = LinearSegmentedColormap.from_list("planning_loss", ["#f6f7f8", "#dce2e7", "#9fadb9"])
    cmap.set_bad("#eeeae5")
    vmax = max(12, float(np.nanmax(matrix)))
    ax.pcolormesh(np.arange(6) - .5, np.arange(9) - .5, matrix,
                  vmin=0, vmax=vmax, cmap=cmap, shading="flat",
                  edgecolors="white", linewidth=.45, rasterized=False)
    ax.set_xlim(-.5, 4.5)
    ax.set_ylim(7.5, -.5)
    for i in range(8):
        for j, (key, _, _) in enumerate(METHODS):
            color = "#2d3b46"
            ax.text(j, i - .15, percentage(matrix[i, j], key), ha="center", va="center",
                    fontsize=7.4, color=color)
            ax.text(j, i + .25, f"({counts[i][j]}/14)", ha="center", va="center",
                    fontsize=5.8, color=color)
    ax.set_yticks(range(8), [label for _, label in GROUPS], fontsize=7.0)
    ax.set_xticks(range(5), [label for _, label, _ in METHODS], fontsize=6.7)
    ax.tick_params(axis="both", length=0, pad=5)
    ax.axhline(3.5, color="white", lw=1.5)
    ax.axvline(1.5, color="white", lw=1.5)
    for spine in ax.spines.values():
        spine.set_visible(False)
    ax.text(-.025, 1.065, "Cap / SLO / m", transform=ax.transAxes,
            ha="right", va="center", fontsize=7.0, color=MUTED)
    ax.text(.5, 1.065, "Mean loss (%); (feasible / 14)", transform=ax.transAxes,
            ha="center", va="center", fontsize=7.0, color=MUTED)
    return matrix, counts


def make_figure(data):
    fig = plt.figure(figsize=(7.65, 3.15), facecolor="white")
    # Keep the top of (a) fixed; raise its bottom to separate labels and times.
    left = fig.add_axes([.0558, .2375, .4231, .5375])
    right = fig.add_axes([.6602, .24, .3356, .55])
    values = individual_losses(left, data["rows"], data["timings"])
    matrix, counts = group_map(right, data["rows"])
    # Titles are centered over each complete panel, including row labels.
    fig.text(.24175, .967, "(a) Loss over optimal solution and feasibility", ha="center", va="top", fontsize=9.4)
    fig.text(.7540, .967, "(b) Mean loss by workload group (%)", ha="center", va="top", fontsize=9.4)
    overhead_y = .10525
    fig.text(.4899, overhead_y, f'Exact: {data["timings"]["mean_planning_seconds"]["exact"]:.2f} s',
             ha="left", va="center", fontsize=7.2, color=MUTED)
    fix_fonts(fig)
    return fig, values, matrix, counts


