def load_data():
    # Preserve the embedded data and its checksum across repeated calls.
    data = deepcopy(DATA)
    canonical = json.dumps(data, sort_keys=True, separators=(",", ":"),
                           ensure_ascii=True, allow_nan=False).encode("utf-8")
    if hashlib.sha256(canonical).hexdigest() != DATA_SHA256:
        raise ValueError("Embedded data checksum mismatch")
    rows = data["rows"]
    if len(rows) != 112 or len({r["case"] for r in rows}) != 112:
        raise ValueError("Expected 112 distinct workloads")
    for group, _ in GROUPS:
        if sum(r["stratum"] == group for r in rows) != 14:
            raise ValueError(f"Incorrect workload count for {group}")
    for r in rows:
        if r["exact_status"] != "optimal" or not np.isfinite(r["exact_ratio"]) or r["exact_ratio"] <= 0:
            raise ValueError(f"Missing certified optimum for {r['case']}")
        for key, _, _ in METHODS:
            entry = r[key]
            if entry["ratio"] is None:
                if key not in {"greedy_construction", "greedy"} or entry["status"] != "construction_failed":
                    raise ValueError(f"Unexpected missing result: {r['case']}/{key}")
            elif entry["status"] not in {"optimal", "feasible", "success", "ok"} or not np.isfinite(entry["ratio"]) or entry["ratio"] <= 0:
                raise ValueError(f"Invalid result: {r['case']}/{key}")
    for (key, _, _), expected in zip(METHODS, EXPECTED_COVERAGE):
        if len(losses(rows, key)) != expected:
            raise ValueError(f"Incorrect coverage for {key}")
    if data["timings"]["timing_lower_bounds"]:
        raise ValueError("Expected complete planning times, without lower bounds")
    timing_audit = recompute_planning_timings()
    planning = ROOT / "results" / "planning"
    stage = json.loads((planning / "stage_timing_audit.json").read_bytes())
    exact = json.loads((planning / "exact_timing_observations.json").read_bytes())
    case_ids = {r["case"] for r in rows}
    for records in (stage["rows"], exact["rows"]):
        if len(records) != len(case_ids) or {r["case"] for r in records} != case_ids:
            raise ValueError("Archived planning timings do not cover the plotted workloads")
    archived_times = {
        "full": fmean(r["greedy_beam_with_preprocessing_seconds"] for r in stage["rows"]),
        "greedy": fmean(r["greedy_with_preprocessing_seconds"] for r in stage["rows"]),
        "greedy_construction": fmean(r["greedy_c_with_preprocessing_seconds"] for r in stage["rows"]),
        "exact": fmean(r["exact_total_seconds"] for r in exact["rows"]),
    }
    for method, seconds in archived_times.items():
        if not np.isclose(seconds, data["timings"]["mean_planning_seconds"][method], rtol=0, atol=1e-12):
            raise ValueError(f"Archived timing does not match Figure 5 for {method}")
    data["timings"]["mean_planning_seconds"].update(archived_times)
    data["timings"]["mean_planning_seconds"].update(timing_audit["mean_planning_seconds"])
    data["timing_audit"] = timing_audit
    return data


def losses(rows, method):
    result = np.asarray([
        100.0 * (1.0 - r[method]["ratio"] / r["exact_ratio"])
        for r in rows if r[method]["ratio"] is not None
    ])
    result[np.abs(result) < 1e-9] = 0.0
    if np.any(result < 0) or not np.all(np.isfinite(result)):
        raise ValueError("Invalid loss relative to Exact")
    return result


def percentage(value, method):
    if not np.isfinite(value):
        return "\u2014"
    if method == "full":
        return "0" if value == 0 else "<0.001" if value < .001 else f"{value:.3f}"
    return f"{value:.2f}"


def fix_fonts(fig):
    """Use actual bundled font files, independent of system font discovery."""
    fonts = Path(matplotlib.get_data_path()) / "fonts" / "ttf"
    for artist in fig.findobj(match=Text):
        weight = artist.get_fontweight()
        bold = weight in {"bold", "semibold", "demibold", "heavy", "black"} or isinstance(weight, (int, float)) and weight >= 600
        filename = "DejaVuSans-Bold.ttf" if bold else "DejaVuSans.ttf"
        artist.set_fontproperties(FontProperties(fname=fonts / filename, size=artist.get_fontsize()))


