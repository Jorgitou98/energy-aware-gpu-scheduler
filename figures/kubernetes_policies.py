def load_data():
    encoded = json.dumps(DATA, sort_keys=True, separators=(",", ":"), allow_nan=False).encode()
    if hashlib.sha256(encoded).hexdigest() != DATA_SHA256:
        raise ValueError("Embedded data checksum mismatch")
    rows = DATA["rows"]
    if DATA["master_seed"] != 0 or len(rows) != 112 or len({r["case"] for r in rows}) != 112:
        raise ValueError("Expected exactly 112 unique seed-0 workloads.")
    for group, _ in GROUPS:
        if sum(r["stratum"] == group for r in rows) != 14:
            raise ValueError(f"Unexpected group size: {group}")
    for row in rows:
        ref = row["greedy_construction"]
        if ref["ratio"] is not None:
            if ref["status"] != "feasible" or not np.isfinite(ref["ratio"]) or ref["ratio"] <= 0:
                raise ValueError(f"Invalid reference in {row['case']}")
        elif ref["status"] != "construction_failed":
            raise ValueError("Missing reference without an explicit construction failure.")
        for policy, _ in POLICIES:
            result = row["results"][policy]
            if (result["ratio"] is None) != (ref["ratio"] is None):
                raise ValueError("The policies must use the same successful cohort.")
            if result["ratio"] is not None:
                if result["status"] != "feasible" or not result["validated"] or not np.isfinite(result["ratio"]) or result["ratio"] <= 0:
                    raise ValueError(f"Invalid policy result in {row['case']}")
            elif result["status"] != "construction_failed" or result["validated"]:
                raise ValueError("Missing policy plan without an explicit construction failure.")
    for policy, _ in POLICIES:
        if len(losses(rows, policy)) != 97:
            raise ValueError("Expected exactly 97 successful paired cases per policy.")
    return DATA


def losses(rows, policy):
    # Do not take absolute values or clip negative losses.
    return np.asarray([100.0 * (1.0 - r["results"][policy]["ratio"] / r["greedy_construction"]["ratio"])
                       for r in rows if r["results"][policy]["ratio"] is not None], dtype=float)


def fix_fonts(fig):
    fonts = Path(matplotlib.get_data_path()) / "fonts" / "ttf"
    for artist in fig.findobj(match=Text):
        weight = artist.get_fontweight()
        bold = weight in {"bold", "semibold", "demibold", "heavy", "black"} or isinstance(weight, (int, float)) and weight >= 600
        name = "DejaVuSans-Bold.ttf" if bold else "DejaVuSans.ttf"
        artist.set_fontproperties(FontProperties(fname=fonts / name, size=artist.get_fontsize()))


