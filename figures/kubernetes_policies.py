def draw_groups(ax, rows):
    means, counts = [], []
    for group, _ in GROUPS:
        selected = [r for r in rows if r["stratum"] == group]
        vv = [losses(selected, policy) for policy, _ in POLICIES]
        means.append([float(v.mean()) for v in vv])
        counts.append([len(v) for v in vv])
    matrix = np.asarray(means)
    cmap = LinearSegmentedColormap.from_list("policy_loss", ["#f6f7f8", "#dce2e7", "#9fadb9"])
    vmax = max(20, float(matrix.max()))
    ax.pcolormesh(np.arange(3) - .5, np.arange(9) - .5, matrix,
                  vmin=0, vmax=vmax, cmap=cmap, shading="flat",
                  edgecolors="white", linewidth=.45, rasterized=False)
    ax.set_xlim(-.5, 1.5)
    ax.set_ylim(7.5, -.5)
    for i in range(8):
        for j in range(2):
            color = "#2d3b46"
            ax.text(j, i - .18, f"{matrix[i, j]:.2f}", ha="center", va="center",
                    fontsize=6.8, color=color)
            ax.text(j, i + .26, f"({counts[i][j]}/14)", ha="center", va="center",
                    fontsize=5.6, color=color)
    ax.set_yticks(range(8), [label for _, label in GROUPS], fontsize=6.0)
    ax.set_xticks([0, 1], ["Least\nAllocated", "Most\nAllocated"], fontsize=6.2)
    ax.tick_params(axis="x", length=0, pad=4)
    ax.tick_params(axis="y", length=0, pad=3)
