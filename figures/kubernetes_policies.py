DATA_SHA256 = '2d6a101e600121cacb814f30bb67ac49dee26974f65ded0f1e21969265be211e'

POLICIES = [("LeastAllocated", "#9ab9bc"), ("MostAllocated", "#d0b795")]
GROUPS = [(f"cap{cap}_{regime}_{load}", f"{cap} / {regime} / {m}")
          for cap in (145, 165) for regime in ("tight", "relaxed")
          for load, m in (("moderate_high", "1.00"), ("high", "1.08"))]
